CREATE TABLE IF NOT EXISTS public.paper_users (
    id TEXT PRIMARY KEY,
    near_account_id TEXT NOT NULL UNIQUE,
    starting_balance DOUBLE PRECISION NOT NULL CHECK (starting_balance > 0),
    realized_pnl DOUBLE PRECISION NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.paper_sessions (
    token_hash CHAR(64) PRIMARY KEY,
    user_id TEXT NOT NULL REFERENCES public.paper_users(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS public.auth_challenges (
    id UUID PRIMARY KEY,
    nonce BYTEA NOT NULL,
    message TEXT NOT NULL,
    recipient TEXT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS public.trades (
    id UUID PRIMARY KEY,
    user_id TEXT NOT NULL REFERENCES public.paper_users(id) ON DELETE CASCADE,
    symbol TEXT NOT NULL,
    quote_asset TEXT NOT NULL DEFAULT 'USDT',
    side TEXT NOT NULL CHECK (side IN ('LONG', 'SHORT')),
    status TEXT NOT NULL CHECK (
        status IN (
            'OPEN',
            'TP1_HIT_TRAILING',
            'TP2_HIT_TRAILING',
            'COMPLETED_TP3',
            'STOPPED_INITIAL_SL',
            'STOPPED_TRAILING_SL',
            'CANCELLED'
        )
    ),
    entry_price DOUBLE PRECISION NOT NULL CHECK (entry_price > 0),
    quantity DOUBLE PRECISION NOT NULL CHECK (quantity > 0),
    initial_stop DOUBLE PRECISION NOT NULL CHECK (initial_stop > 0),
    tp1 DOUBLE PRECISION NOT NULL CHECK (tp1 > 0),
    tp2 DOUBLE PRECISION NOT NULL CHECK (tp2 > 0),
    tp3 DOUBLE PRECISION NOT NULL CHECK (tp3 > 0),
    trailing_percent DOUBLE PRECISION NOT NULL CHECK (trailing_percent > 0),
    trailing_active BOOLEAN NOT NULL DEFAULT FALSE,
    trailing_stop DOUBLE PRECISION,
    highest_price_since_tp1 DOUBLE PRECISION,
    lowest_price_since_tp1 DOUBLE PRECISION,
    current_price DOUBLE PRECISION NOT NULL CHECK (current_price > 0),
    exit_price DOUBLE PRECISION,
    realized_pnl DOUBLE PRECISION,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ,
    notes TEXT
);

CREATE TABLE IF NOT EXISTS public.trade_events (
    id UUID PRIMARY KEY,
    trade_id UUID NOT NULL REFERENCES public.trades(id) ON DELETE CASCADE,
    event_key TEXT NOT NULL UNIQUE,
    event_type TEXT NOT NULL,
    event_payload_json JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.risk_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL UNIQUE REFERENCES public.paper_users(id) ON DELETE CASCADE,
    paper_equity DOUBLE PRECISION NOT NULL CHECK (paper_equity > 0),
    max_open_positions INTEGER NOT NULL CHECK (max_open_positions > 0),
    max_risk_per_trade_percent DOUBLE PRECISION NOT NULL CHECK (max_risk_per_trade_percent > 0),
    max_daily_loss_percent DOUBLE PRECISION NOT NULL CHECK (max_daily_loss_percent > 0),
    kill_switch_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.daily_stats (
    user_id TEXT NOT NULL REFERENCES public.paper_users(id) ON DELETE CASCADE,
    day_utc DATE NOT NULL,
    asset TEXT NOT NULL DEFAULT 'USDT',
    starting_equity DOUBLE PRECISION NOT NULL,
    realized_pnl DOUBLE PRECISION NOT NULL DEFAULT 0,
    new_trades_blocked BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (user_id, day_utc, asset)
);

CREATE TABLE IF NOT EXISTS public.paper_asset_balances (
    user_id TEXT NOT NULL REFERENCES public.paper_users(id) ON DELETE CASCADE,
    asset TEXT NOT NULL,
    starting_balance DOUBLE PRECISION NOT NULL DEFAULT 0,
    realized_pnl DOUBLE PRECISION NOT NULL DEFAULT 0,
    PRIMARY KEY (user_id, asset)
);

CREATE TABLE IF NOT EXISTS public.app_settings (
    key TEXT PRIMARY KEY,
    value_json JSONB NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_trade_events_created
    ON public.trade_events (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_trade_events_trade
    ON public.trade_events (trade_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_trades_user_created
    ON public.trades (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_trades_user_status_created
    ON public.trades (user_id, status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_sessions_expiry
    ON public.paper_sessions (expires_at);
CREATE INDEX IF NOT EXISTS idx_challenges_expiry
    ON public.auth_challenges (expires_at);
CREATE INDEX IF NOT EXISTS idx_daily_stats_user_day
    ON public.daily_stats (user_id, day_utc DESC);

