CREATE TABLE IF NOT EXISTS public.auth_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS auth_sessions_expiry_idx ON public.auth_sessions (expires_at);
CREATE INDEX IF NOT EXISTS auth_sessions_user_idx ON public.auth_sessions (user_id);

CREATE TABLE IF NOT EXISTS public.auth_rate_limits (
    rate_key CHAR(64) PRIMARY KEY,
    request_count INTEGER NOT NULL DEFAULT 0,
    window_ends_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS auth_rate_limits_window_idx ON public.auth_rate_limits (window_ends_at);

ALTER TABLE public.auth_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.auth_rate_limits ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.auth_sessions, public.auth_rate_limits FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.auth_sessions_id_seq FROM anon, authenticated;
