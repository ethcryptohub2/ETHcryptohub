CREATE TABLE IF NOT EXISTS public.market_signals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    signal_key VARCHAR(255) NOT NULL UNIQUE,
    symbol VARCHAR(30) NOT NULL,
    timeframe VARCHAR(4) NOT NULL CHECK (timeframe IN ('5m', '15m', '1h', '4h')),
    side VARCHAR(5) NOT NULL CHECK (side IN ('LONG', 'SHORT')),
    setup_score INTEGER NOT NULL CHECK (setup_score BETWEEN 0 AND 100),
    entry_price NUMERIC(30, 12) NOT NULL CHECK (entry_price > 0),
    entry_zone_low NUMERIC(30, 12) NOT NULL CHECK (entry_zone_low > 0),
    entry_zone_high NUMERIC(30, 12) NOT NULL CHECK (entry_zone_high >= entry_zone_low),
    initial_stop NUMERIC(30, 12) NOT NULL CHECK (initial_stop > 0),
    tp1 NUMERIC(30, 12) NOT NULL CHECK (tp1 > 0),
    tp2 NUMERIC(30, 12) NOT NULL CHECK (tp2 > 0),
    tp3 NUMERIC(30, 12) NOT NULL CHECK (tp3 > 0),
    latest_price NUMERIC(30, 12) NOT NULL CHECK (latest_price > 0),
    last_candle_close_at TIMESTAMPTZ NOT NULL,
    generated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    repeated_scan_count BIGINT NOT NULL DEFAULT 0 CHECK (repeated_scan_count >= 0),
    signal_update_version INTEGER NOT NULL DEFAULT 0 CHECK (signal_update_version >= 0),
    last_signal_updated_at TIMESTAMPTZ,
    status VARCHAR(24) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'TP1_HIT', 'TP2_HIT', 'TP3_HIT', 'STOP_LOSS_HIT', 'EXPIRED', 'ENTRY_INVALIDATED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS market_signals_active_expiry_idx
    ON public.market_signals (expires_at) WHERE status IN ('ACTIVE', 'TP1_HIT', 'TP2_HIT');
CREATE INDEX IF NOT EXISTS market_signals_created_idx ON public.market_signals (generated_at DESC);

CREATE TABLE IF NOT EXISTS public.signal_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    signal_id BIGINT NOT NULL REFERENCES public.market_signals(id) ON DELETE CASCADE,
    idempotency_key VARCHAR(320) NOT NULL UNIQUE,
    event_type VARCHAR(24) NOT NULL
        CHECK (event_type IN ('NEW_SIGNAL', 'SIGNAL_UPDATED', 'TP1_HIT', 'TP2_HIT', 'TP3_HIT', 'STOP_LOSS_HIT', 'SIGNAL_EXPIRED', 'ENTRY_INVALIDATED')),
    payload JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS signal_events_pending_idx
    ON public.signal_events (created_at) WHERE processed_at IS NULL;

CREATE TABLE IF NOT EXISTS public.user_notification_preferences (
    user_id INTEGER PRIMARY KEY REFERENCES public.users(id) ON DELETE CASCADE,
    push_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    sound_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    long_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    short_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    high_conviction_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    tp1_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    tp2_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    tp3_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    stop_loss_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    expiry_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    minimum_setup_score INTEGER NOT NULL DEFAULT 60 CHECK (minimum_setup_score BETWEEN 0 AND 100),
    alarm_volume NUMERIC(3, 2) NOT NULL DEFAULT 0.70 CHECK (alarm_volume BETWEEN 0 AND 1),
    quiet_hours_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    quiet_hours_start TIME NOT NULL DEFAULT '22:00',
    quiet_hours_end TIME NOT NULL DEFAULT '07:00',
    quiet_hours_timezone VARCHAR(64) NOT NULL DEFAULT 'UTC',
    do_not_disturb BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.push_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    endpoint TEXT NOT NULL UNIQUE,
    p256dh TEXT NOT NULL,
    auth TEXT NOT NULL,
    device_type VARCHAR(16) NOT NULL DEFAULT 'browser' CHECK (device_type IN ('browser', 'mobile', 'pwa')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_used_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS push_subscriptions_user_idx ON public.push_subscriptions (user_id);

CREATE TABLE IF NOT EXISTS public.user_signal_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    signal_id BIGINT NOT NULL REFERENCES public.market_signals(id) ON DELETE CASCADE,
    event_id BIGINT NOT NULL REFERENCES public.signal_events(id) ON DELETE CASCADE,
    read_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, event_id)
);
CREATE INDEX IF NOT EXISTS user_signal_notifications_unread_idx
    ON public.user_signal_notifications (user_id, created_at DESC) WHERE read_at IS NULL;
CREATE INDEX IF NOT EXISTS user_signal_notifications_history_idx
    ON public.user_signal_notifications (user_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.push_delivery_attempts (
    notification_id BIGINT NOT NULL REFERENCES public.user_signal_notifications(id) ON DELETE CASCADE,
    subscription_id BIGINT NOT NULL REFERENCES public.push_subscriptions(id) ON DELETE CASCADE,
    status VARCHAR(12) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'SENDING', 'SENT', 'FAILED')),
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    last_error TEXT,
    delivered_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (notification_id, subscription_id)
);
CREATE INDEX IF NOT EXISTS push_delivery_retry_idx
    ON public.push_delivery_attempts (updated_at) WHERE status IN ('PENDING', 'FAILED') AND attempts < 4;

CREATE TABLE IF NOT EXISTS public.notification_system_settings (
    singleton BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (singleton),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    validity_minutes JSONB NOT NULL DEFAULT '{"5m":10,"15m":25,"1h":60,"4h":240}'::JSONB,
    minimum_setup_score INTEGER NOT NULL DEFAULT 60 CHECK (minimum_setup_score BETWEEN 0 AND 100),
    high_conviction_score INTEGER NOT NULL DEFAULT 80 CHECK (high_conviction_score BETWEEN 0 AND 100),
    entry_zone_atr_fraction NUMERIC(4, 3) NOT NULL DEFAULT 0.250 CHECK (entry_zone_atr_fraction BETWEEN 0.01 AND 2),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
INSERT INTO public.notification_system_settings (singleton)
VALUES (TRUE) ON CONFLICT (singleton) DO NOTHING;

