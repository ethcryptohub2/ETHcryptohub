CREATE TABLE IF NOT EXISTS public.scanner_coin_configs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol VARCHAR(30) NOT NULL,
    base_asset VARCHAR(20) NOT NULL,
    quote_asset VARCHAR(12) NOT NULL DEFAULT 'USDT' CHECK (quote_asset = 'USDT'),
    exchange VARCHAR(16) NOT NULL DEFAULT 'BINANCE' CHECK (exchange = 'BINANCE'),
    contract_type VARCHAR(16) NOT NULL DEFAULT 'PERPETUAL' CHECK (contract_type = 'PERPETUAL'),
    trading_status VARCHAR(24) NOT NULL,
    is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    is_admin_disabled BOOLEAN NOT NULL DEFAULT FALSE,
    disable_reason TEXT,
    first_listed_at TIMESTAMPTZ,
    last_synced_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (exchange, symbol)
);

CREATE INDEX IF NOT EXISTS scanner_coin_configs_enabled_idx
    ON public.scanner_coin_configs (exchange, is_enabled, trading_status, symbol);
CREATE INDEX IF NOT EXISTS scanner_coin_configs_symbol_idx
    ON public.scanner_coin_configs (symbol);

CREATE TABLE IF NOT EXISTS public.scanner_sync_state (
    singleton BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (singleton),
    last_attempt_at TIMESTAMPTZ,
    last_success_at TIMESTAMPTZ,
    discovered_count INTEGER NOT NULL DEFAULT 0,
    newly_added_count INTEGER NOT NULL DEFAULT 0,
    updated_count INTEGER NOT NULL DEFAULT 0,
    inactive_count INTEGER NOT NULL DEFAULT 0,
    exchange_status VARCHAR(16) NOT NULL DEFAULT 'NEVER_RUN'
        CHECK (exchange_status IN ('NEVER_RUN', 'OK', 'ERROR')),
    last_error TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
INSERT INTO public.scanner_sync_state (singleton)
VALUES (TRUE) ON CONFLICT (singleton) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.scanner_coin_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action VARCHAR(32) NOT NULL,
    symbol VARCHAR(30),
    admin_user_id INTEGER REFERENCES public.users(id) ON DELETE SET NULL,
    previous_state JSONB,
    new_state JSONB,
    reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS scanner_coin_audit_created_idx
    ON public.scanner_coin_audit_log (created_at DESC);
CREATE INDEX IF NOT EXISTS scanner_coin_audit_symbol_idx
    ON public.scanner_coin_audit_log (symbol, created_at DESC);

CREATE TABLE IF NOT EXISTS public.scanner_admin_rate_limits (
    user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    action VARCHAR(16) NOT NULL,
    window_started_at TIMESTAMPTZ NOT NULL,
    request_count INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (user_id, action, window_started_at)
);

CREATE TABLE IF NOT EXISTS public.scanner_candidate_snapshots (
    symbol VARCHAR(30) NOT NULL,
    timeframe VARCHAR(4) NOT NULL CHECK (timeframe IN ('5m', '15m', '1h', '4h')),
    exchange VARCHAR(16) NOT NULL DEFAULT 'BINANCE' CHECK (exchange = 'BINANCE'),
    candidate_json JSONB NOT NULL,
    scanned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (symbol, timeframe)
);
CREATE INDEX IF NOT EXISTS scanner_candidate_snapshots_scanned_idx
    ON public.scanner_candidate_snapshots (timeframe, scanned_at DESC);

