CREATE OR REPLACE FUNCTION public.create_registration_trial()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    trial_plan_id BIGINT;
BEGIN
    SELECT id INTO trial_plan_id
      FROM public.subscription_plans
     WHERE plan_key = 'FREE_TRIAL'
     LIMIT 1;
    IF trial_plan_id IS NULL THEN
        RAISE EXCEPTION 'Free trial subscription plan is not configured.';
    END IF;

    INSERT INTO public.subscriptions
        (user_id, plan_id, subscription_status, trial_started_at, trial_expires_at)
    VALUES (NEW.id, trial_plan_id, 'FREE_TRIAL', NEW.created_at, NEW.created_at + INTERVAL '7 days')
    ON CONFLICT (user_id) DO NOTHING;

    INSERT INTO public.subscription_audit_log
        (user_id, event_type, plan_id, new_status, details)
    SELECT NEW.id, 'TRIAL_CREATED', trial_plan_id, 'FREE_TRIAL',
           jsonb_build_object('trialStartedAt', NEW.created_at, 'trialExpiresAt', NEW.created_at + INTERVAL '7 days')
     WHERE NOT EXISTS (
        SELECT 1 FROM public.subscription_audit_log
         WHERE user_id = NEW.id AND event_type = 'TRIAL_CREATED'
     );
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS users_create_registration_trial ON public.users;
CREATE TRIGGER users_create_registration_trial
AFTER INSERT ON public.users
FOR EACH ROW EXECUTE FUNCTION public.create_registration_trial();

INSERT INTO public.subscriptions
    (user_id, plan_id, subscription_status, trial_started_at, trial_expires_at)
SELECT u.id, p.id, 'FREE_TRIAL', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP + INTERVAL '7 days'
  FROM public.users AS u
 CROSS JOIN public.subscription_plans AS p
 WHERE p.plan_key = 'FREE_TRIAL'
ON CONFLICT (user_id) DO NOTHING;

INSERT INTO public.subscription_audit_log
    (user_id, event_type, plan_id, new_status, details)
SELECT s.user_id, 'TRIAL_CREATED', s.plan_id, 'FREE_TRIAL',
       jsonb_build_object('trialStartedAt', s.trial_started_at, 'trialExpiresAt', s.trial_expires_at, 'source', 'migration_launch_grace')
  FROM public.subscriptions AS s
 WHERE s.subscription_status = 'FREE_TRIAL'
   AND NOT EXISTS (
       SELECT 1 FROM public.subscription_audit_log AS a
        WHERE a.user_id = s.user_id AND a.event_type = 'TRIAL_CREATED'
   );

