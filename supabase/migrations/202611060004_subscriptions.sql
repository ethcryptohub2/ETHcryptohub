CREATE TABLE IF NOT EXISTS public.subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL UNIQUE REFERENCES public.users(id) ON DELETE CASCADE,
    plan_id BIGINT REFERENCES public.subscription_plans(id),
    subscription_status VARCHAR(24) NOT NULL DEFAULT 'FREE_TRIAL'
        CHECK (subscription_status IN ('FREE_TRIAL', 'PREMIUM_ACTIVE', 'TRIAL_EXPIRED', 'PREMIUM_EXPIRED')),
    trial_started_at TIMESTAMPTZ NOT NULL,
    trial_expires_at TIMESTAMPTZ NOT NULL,
    premium_started_at TIMESTAMPTZ,
    premium_expires_at TIMESTAMPTZ,
    activated_by_code_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (trial_expires_at > trial_started_at),
    CHECK (premium_expires_at IS NULL OR premium_started_at IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS subscriptions_status_expiry_idx
    ON public.subscriptions (subscription_status, premium_expires_at, trial_expires_at);

CREATE TABLE IF NOT EXISTS public.license_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_hash CHAR(64) NOT NULL UNIQUE,
    plan_id BIGINT NOT NULL REFERENCES public.subscription_plans(id),
    duration_days INTEGER NOT NULL CHECK (duration_days > 0),
    purchase_price_usd NUMERIC(10, 2) NOT NULL CHECK (purchase_price_usd >= 0),
    payment_reference VARCHAR(160),
    code_status VARCHAR(12) NOT NULL DEFAULT 'UNUSED'
        CHECK (code_status IN ('UNUSED', 'REDEEMED', 'EXPIRED', 'REVOKED')),
    assigned_user_email CITEXT,
    redeemed_by_user_id INTEGER REFERENCES public.users(id) ON DELETE SET NULL,
    redeemed_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ,
    admin_note TEXT,
    created_by_admin_id INTEGER REFERENCES public.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((code_status = 'REDEEMED') = (redeemed_at IS NOT NULL AND redeemed_by_user_id IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS license_codes_status_created_idx
    ON public.license_codes (code_status, created_at DESC);
CREATE INDEX IF NOT EXISTS license_codes_assigned_email_idx
    ON public.license_codes (assigned_user_email);

ALTER TABLE public.subscriptions
