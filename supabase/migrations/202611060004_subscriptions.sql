CREATE TABLE IF NOT EXISTS public.subscription_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    plan_id BIGINT REFERENCES public.subscription_plans(id),
    license_code_id BIGINT REFERENCES public.license_codes(id) ON DELETE SET NULL,
    amount NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (amount >= 0),
    currency VARCHAR(3) NOT NULL DEFAULT 'USD',
    payment_status VARCHAR(24) NOT NULL
        CHECK (payment_status IN ('NOT_REQUIRED', 'MANUAL_VERIFIED', 'COMPLIMENTARY')),
    payment_reference VARCHAR(160),
    transaction_type VARCHAR(24) NOT NULL
        CHECK (transaction_type IN ('LICENSE_REDEMPTION', 'COMPLIMENTARY', 'ADMIN_EXTENSION')),
    previous_expiry TIMESTAMPTZ,
    new_expiry TIMESTAMPTZ,
    created_by_admin_id INTEGER REFERENCES public.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS subscription_transactions_user_created_idx
    ON public.subscription_transactions (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS subscription_transactions_code_idx
    ON public.subscription_transactions (license_code_id);

CREATE TABLE IF NOT EXISTS public.subscription_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
