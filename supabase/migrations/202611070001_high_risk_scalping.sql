CREATE TABLE IF NOT EXISTS public.high_risk_scalping_settings (
    singleton BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (singleton),
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    enabled_timeframes JSONB NOT NULL DEFAULT '["1m","3m","5m","15m"]'::JSONB,
    minimum_setup_score INTEGER NOT NULL DEFAULT 75 CHECK (minimum_setup_score BETWEEN 0 AND 100),
    minimum_quote_volume NUMERIC(24, 2) NOT NULL DEFAULT 5000000 CHECK (minimum_quote_volume >= 0),
    minimum_relative_volume NUMERIC(8, 3) NOT NULL DEFAULT 1.5 CHECK (minimum_relative_volume >= 1),
    entry_validity_minutes JSONB NOT NULL DEFAULT '{"1m":5,"3m":8,"5m":12,"15m":20}'::JSONB,
    signal_validity_minutes JSONB NOT NULL DEFAULT '{"1m":15,"3m":30,"5m":60,"15m":120}'::JSONB,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
INSERT INTO public.high_risk_scalping_settings (singleton)
VALUES (TRUE) ON CONFLICT (singleton) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.high_risk_scalping_signals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    signal_key VARCHAR(255) NOT NULL UNIQUE,
    symbol VARCHAR(30) NOT NULL,
    timeframe VARCHAR(3) NOT NULL CHECK (timeframe IN ('1m', '3m', '5m', '15m')),
    side VARCHAR(5) NOT NULL CHECK (side IN ('LONG', 'SHORT')),
    setup_score INTEGER NOT NULL CHECK (setup_score BETWEEN 0 AND 100),
    entry_price NUMERIC(30, 12) NOT NULL CHECK (entry_price > 0),
    entry_zone_low NUMERIC(30, 12) NOT NULL CHECK (entry_zone_low > 0),
    entry_zone_high NUMERIC(30, 12) NOT NULL CHECK (entry_zone_high >= entry_zone_low),
    initial_stop NUMERIC(30, 12) NOT NULL CHECK (initial_stop > 0),
    tp1 NUMERIC(30, 12) NOT NULL CHECK (tp1 > 0),
    tp2 NUMERIC(30, 12) NOT NULL CHECK (tp2 > 0),
    last_price NUMERIC(30, 12) NOT NULL CHECK (last_price > 0),
    candle_open_at TIMESTAMPTZ NOT NULL,
    generated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    entry_expires_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    lifecycle_status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE'
        CHECK (lifecycle_status IN ('ACTIVE', 'MISSED', 'EXPIRED', 'INVALIDATED', 'COMPLETED')),
    setup_context JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS high_risk_scalping_active_setup_idx
    ON public.high_risk_scalping_signals (symbol, timeframe, side)
    WHERE lifecycle_status = 'ACTIVE';
CREATE INDEX IF NOT EXISTS high_risk_scalping_history_idx
    ON public.high_risk_scalping_signals (generated_at DESC);
CREATE INDEX IF NOT EXISTS high_risk_scalping_active_expiry_idx
    ON public.high_risk_scalping_signals (entry_expires_at)
    WHERE lifecycle_status = 'ACTIVE';

CREATE TABLE IF NOT EXISTS public.high_risk_scalping_user_states (
    user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    signal_id BIGINT NOT NULL REFERENCES public.high_risk_scalping_signals(id) ON DELETE CASCADE,
    state VARCHAR(12) NOT NULL CHECK (state = 'ENTERED'),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, signal_id)
);

CREATE TABLE IF NOT EXISTS public.high_risk_scalping_preferences (
    user_id INTEGER PRIMARY KEY REFERENCES public.users(id) ON DELETE CASCADE,
    push_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.high_risk_scalping_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    signal_id BIGINT NOT NULL REFERENCES public.high_risk_scalping_signals(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, signal_id)
);

