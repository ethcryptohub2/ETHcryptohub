    ADD COLUMN IF NOT EXISTS scanner_type VARCHAR(16) NOT NULL DEFAULT 'STANDARD',
    ADD COLUMN IF NOT EXISTS exchange VARCHAR(16) NOT NULL DEFAULT 'BINANCE',
    ADD COLUMN IF NOT EXISTS strategy_name VARCHAR(80) NOT NULL DEFAULT 'STANDARD_TECHNICAL',
    ADD COLUMN IF NOT EXISTS entry_expires_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS candle_open_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS entry_status VARCHAR(16) NOT NULL DEFAULT 'OPEN',
    ADD COLUMN IF NOT EXISTS actual_entry_price NUMERIC(30, 12),
    ADD COLUMN IF NOT EXISTS actual_exit_price NUMERIC(30, 12),
    ADD COLUMN IF NOT EXISTS realized_pnl NUMERIC(30, 12),
    ADD COLUMN IF NOT EXISTS simulated_pnl NUMERIC(30, 12),
    ADD COLUMN IF NOT EXISTS research_snapshot JSONB NOT NULL DEFAULT '{}'::JSONB,
    ADD COLUMN IF NOT EXISTS source_metadata JSONB NOT NULL DEFAULT '{}'::JSONB,
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ADD COLUMN IF NOT EXISTS closed_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS lifecycle_checked_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS legacy_scalping_signal_id BIGINT;

UPDATE public.market_signals
   SET entry_expires_at = COALESCE(entry_expires_at, expires_at),
       lifecycle_checked_at = COALESCE(lifecycle_checked_at, generated_at),
       updated_at = GREATEST(updated_at, generated_at)
 WHERE entry_expires_at IS NULL;

UPDATE public.market_signals
   SET lifecycle_checked_at = generated_at
 WHERE lifecycle_checked_at IS NULL;

ALTER TABLE public.market_signals
    ALTER COLUMN lifecycle_checked_at SET DEFAULT CURRENT_TIMESTAMP,
    ALTER COLUMN lifecycle_checked_at SET NOT NULL;

ALTER TABLE public.market_signals
