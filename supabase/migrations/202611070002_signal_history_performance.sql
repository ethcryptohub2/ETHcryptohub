    ALTER COLUMN last_candle_close_at DROP NOT NULL;

ALTER TABLE public.market_signals
    DROP CONSTRAINT IF EXISTS market_signals_timeframe_check,
    DROP CONSTRAINT IF EXISTS market_signals_status_check,
    DROP CONSTRAINT IF EXISTS market_signals_scanner_type_check,
    DROP CONSTRAINT IF EXISTS market_signals_entry_status_check;

ALTER TABLE public.market_signals
    ADD CONSTRAINT market_signals_timeframe_check
        CHECK (timeframe IN ('1m', '3m', '5m', '15m', '1h', '4h')),
    ADD CONSTRAINT market_signals_status_check
        CHECK (status IN ('ACTIVE', 'TP1_HIT', 'TP2_HIT', 'TP3_HIT', 'COMPLETED', 'STOP_LOSS_HIT', 'EXPIRED', 'ENTRY_INVALIDATED', 'MISSED', 'AMBIGUOUS')),
    ADD CONSTRAINT market_signals_scanner_type_check
        CHECK (scanner_type IN ('STANDARD', 'HIGH_RISK')),
    ADD CONSTRAINT market_signals_entry_status_check
        CHECK (entry_status IN ('OPEN', 'ENTERED', 'MISSED', 'EXPIRED', 'INVALIDATED'));

CREATE UNIQUE INDEX IF NOT EXISTS market_signals_legacy_scalping_id_idx
    ON public.market_signals (legacy_scalping_signal_id)
    WHERE legacy_scalping_signal_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS market_signals_history_filter_idx
    ON public.market_signals (scanner_type, generated_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS market_signals_lifecycle_idx
    ON public.market_signals (status, entry_expires_at)
    WHERE status IN ('ACTIVE', 'TP1_HIT', 'TP2_HIT');
CREATE UNIQUE INDEX IF NOT EXISTS market_signals_high_risk_active_setup_idx
    ON public.market_signals (symbol, timeframe, side)
    WHERE scanner_type = 'HIGH_RISK' AND status IN ('ACTIVE', 'TP1_HIT', 'TP2_HIT');

