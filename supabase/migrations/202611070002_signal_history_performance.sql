CREATE TABLE IF NOT EXISTS public.signal_research_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    signal_id BIGINT NOT NULL UNIQUE REFERENCES public.market_signals(id) ON DELETE RESTRICT,
    indicator_snapshot JSONB NOT NULL DEFAULT '{}'::JSONB,
    volume_snapshot JSONB NOT NULL DEFAULT '{}'::JSONB,
    market_structure_snapshot JSONB NOT NULL DEFAULT '{}'::JSONB,
    derivatives_snapshot JSONB NOT NULL DEFAULT '{}'::JSONB,
    sentiment_snapshot JSONB NOT NULL DEFAULT '{}'::JSONB,
    data_sources JSONB NOT NULL DEFAULT '[]'::JSONB,
    captured_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.signal_performance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    signal_id BIGINT NOT NULL UNIQUE REFERENCES public.market_signals(id) ON DELETE RESTRICT,
    entry_price NUMERIC(30, 12) NOT NULL CHECK (entry_price > 0),
    exit_price NUMERIC(30, 12) CHECK (exit_price > 0),
    realized_pnl NUMERIC(30, 12),
    simulated_pnl NUMERIC(30, 12),
    pnl_percentage NUMERIC(12, 6),
    result_type VARCHAR(24) NOT NULL
        CHECK (result_type IN ('TP2_SIMULATED', 'TP3_SIMULATED', 'STOP_LOSS_SIMULATED', 'USER_RECORDED')),
    holding_duration_seconds BIGINT CHECK (holding_duration_seconds >= 0),
    calculation_method VARCHAR(80) NOT NULL,
    calculated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.signal_user_entries (
    user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    signal_id BIGINT NOT NULL REFERENCES public.market_signals(id) ON DELETE RESTRICT,
    entry_price NUMERIC(30, 12) CHECK (entry_price > 0),
    exit_price NUMERIC(30, 12) CHECK (exit_price > 0),
    realized_pnl NUMERIC(30, 12),
    status VARCHAR(16) NOT NULL DEFAULT 'ENTERED'
        CHECK (status IN ('ENTERED', 'CLOSED')),
    entered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, signal_id),
    CHECK (
        (status = 'ENTERED' AND closed_at IS NULL) OR
        (status = 'CLOSED' AND closed_at IS NOT NULL)
    )
);

