    ('exchange', 'Exchange Announcements'),
    ('onchain', 'On-chain Activity'),
    ('economics', 'Economic Events'),
    ('regulation', 'Regulation'),
    ('technology', 'Technology')
ON CONFLICT (category_key) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.news_sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_key VARCHAR(80) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    adapter VARCHAR(24) NOT NULL CHECK (adapter IN ('CRYPTOPANIC', 'RSS', 'JSON_API')),
    source_type VARCHAR(32) NOT NULL
        CHECK (source_type IN ('CRYPTO_API', 'RSS', 'EXCHANGE_ANNOUNCEMENT', 'ONCHAIN_ACTIVITY', 'ECONOMIC_CALENDAR', 'JSON_API')),
    endpoint TEXT NOT NULL,
    credential_ciphertext TEXT,
    configuration JSONB NOT NULL DEFAULT '{}'::JSONB,
    allowed_categories TEXT[] NOT NULL DEFAULT ARRAY['market']::TEXT[],
    is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    is_trusted BOOLEAN NOT NULL DEFAULT FALSE,
    auto_publish BOOLEAN NOT NULL DEFAULT FALSE,
    refresh_interval_minutes INTEGER CHECK (refresh_interval_minutes BETWEEN 5 AND 1440),
    last_fetch_at TIMESTAMPTZ,
    last_success_at TIMESTAMPTZ,
    last_error TEXT,
    archived_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS news_sources_enabled_idx
    ON public.news_sources (is_enabled, source_type);

CREATE TABLE IF NOT EXISTS public.news_articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT NOT NULL REFERENCES public.news_sources(id) ON DELETE RESTRICT,
    external_id VARCHAR(300) NOT NULL,
    article_key CHAR(64) NOT NULL UNIQUE,
    canonical_url TEXT NOT NULL UNIQUE,
    headline VARCHAR(500) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    original_url TEXT NOT NULL,
    source_name VARCHAR(120) NOT NULL,
    published_at TIMESTAMPTZ,
    fetched_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ticker_symbols TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    category_id BIGINT NOT NULL REFERENCES public.news_categories(id) ON DELETE RESTRICT,
    sentiment VARCHAR(16) NOT NULL DEFAULT 'UNAVAILABLE'
        CHECK (sentiment IN ('BULLISH', 'BEARISH', 'NEUTRAL', 'UNAVAILABLE')),
    priority VARCHAR(16) NOT NULL DEFAULT 'NORMAL'
        CHECK (priority IN ('LOW', 'NORMAL', 'HIGH', 'BREAKING')),
    verification_status VARCHAR(16) NOT NULL DEFAULT 'PENDING'
        CHECK (verification_status IN ('PENDING', 'VERIFIED', 'REJECTED')),
    publication_status VARCHAR(16) NOT NULL DEFAULT 'PENDING'
        CHECK (publication_status IN ('PENDING', 'PUBLISHED', 'ARCHIVED', 'REJECTED')),
    published_by INTEGER REFERENCES public.users(id) ON DELETE SET NULL,
    published_at_admin TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (source_id, external_id)
);
CREATE INDEX IF NOT EXISTS news_articles_published_idx
    ON public.news_articles (published_at DESC, id DESC)
    WHERE publication_status = 'PUBLISHED' AND verification_status = 'VERIFIED';
CREATE INDEX IF NOT EXISTS news_articles_category_idx
    ON public.news_articles (category_id, published_at DESC);
CREATE INDEX IF NOT EXISTS news_articles_tickers_idx
    ON public.news_articles USING GIN (ticker_symbols);
CREATE INDEX IF NOT EXISTS news_articles_review_idx
    ON public.news_articles (created_at DESC)
    WHERE publication_status = 'PENDING' OR verification_status = 'PENDING';

CREATE TABLE IF NOT EXISTS public.news_processing_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id BIGINT REFERENCES public.news_sources(id) ON DELETE SET NULL,
    source_name VARCHAR(120) NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('SUCCESS', 'PARTIAL', 'FAILED')),
    fetched_count INTEGER NOT NULL DEFAULT 0 CHECK (fetched_count >= 0),
    stored_count INTEGER NOT NULL DEFAULT 0 CHECK (stored_count >= 0),
    duplicate_count INTEGER NOT NULL DEFAULT 0 CHECK (duplicate_count >= 0),
    published_count INTEGER NOT NULL DEFAULT 0 CHECK (published_count >= 0),
    error_message TEXT,
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS news_processing_logs_recent_idx
    ON public.news_processing_logs (started_at DESC);
CREATE INDEX IF NOT EXISTS news_processing_logs_source_idx
    ON public.news_processing_logs (source_id, started_at DESC);

CREATE TABLE IF NOT EXISTS public.news_user_preferences (
    user_id INTEGER PRIMARY KEY REFERENCES public.users(id) ON DELETE CASCADE,
    enabled_categories TEXT[] NOT NULL DEFAULT ARRAY['market', 'exchange', 'onchain', 'economics', 'regulation', 'technology']::TEXT[],
    ticker_symbols TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    breaking_notifications BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.news_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    article_id BIGINT NOT NULL REFERENCES public.news_articles(id) ON DELETE CASCADE,
    read_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, article_id)
);
CREATE INDEX IF NOT EXISTS news_notifications_unread_idx
    ON public.news_notifications (user_id, created_at DESC)
    WHERE read_at IS NULL;

CREATE TABLE IF NOT EXISTS public.platform_settings (
    singleton BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (singleton),
    news_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    automatic_fetching BOOLEAN NOT NULL DEFAULT TRUE,
    automatic_publishing BOOLEAN NOT NULL DEFAULT FALSE,
    refresh_interval_minutes INTEGER NOT NULL DEFAULT 15 CHECK (refresh_interval_minutes BETWEEN 5 AND 1440),
    allowed_categories TEXT[] NOT NULL DEFAULT ARRAY['market', 'exchange', 'onchain', 'economics', 'regulation', 'technology']::TEXT[],
    sentiment_analysis_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    breaking_news_alerts_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    duplicate_detection_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    maximum_articles INTEGER NOT NULL DEFAULT 5000 CHECK (maximum_articles BETWEEN 100 AND 100000),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by INTEGER REFERENCES public.users(id) ON DELETE SET NULL
);
