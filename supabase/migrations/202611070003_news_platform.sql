DROP POLICY IF EXISTS news_categories_authenticated_read ON public.news_categories;
CREATE POLICY news_categories_authenticated_read
    ON public.news_categories FOR SELECT TO authenticated
    USING (is_enabled);

DROP POLICY IF EXISTS news_articles_published_read ON public.news_articles;
CREATE POLICY news_articles_published_read
    ON public.news_articles FOR SELECT TO authenticated
    USING (
        publication_status = 'PUBLISHED'
        AND verification_status = 'VERIFIED'
        AND CASE
            WHEN (auth.jwt() ->> 'app_user_id') ~ '^[0-9]+$'
            THEN (auth.jwt() ->> 'app_user_id')::BIGINT > 0
            ELSE FALSE
        END
    );

DROP POLICY IF EXISTS news_user_preferences_self ON public.news_user_preferences;
CREATE POLICY news_user_preferences_self
    ON public.news_user_preferences FOR ALL TO authenticated
    USING (
        CASE
            WHEN (auth.jwt() ->> 'app_user_id') ~ '^[0-9]+$'
            THEN (auth.jwt() ->> 'app_user_id')::INTEGER = user_id
            ELSE FALSE
        END
    )
    WITH CHECK (
        CASE
            WHEN (auth.jwt() ->> 'app_user_id') ~ '^[0-9]+$'
            THEN (auth.jwt() ->> 'app_user_id')::INTEGER = user_id
            ELSE FALSE
        END
    );

DROP POLICY IF EXISTS news_notifications_self_read ON public.news_notifications;
CREATE POLICY news_notifications_self_read
    ON public.news_notifications FOR SELECT TO authenticated
    USING (
        CASE
            WHEN (auth.jwt() ->> 'app_user_id') ~ '^[0-9]+$'
            THEN (auth.jwt() ->> 'app_user_id')::INTEGER = user_id
            ELSE FALSE
        END
    );

