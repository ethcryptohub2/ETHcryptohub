CREATE TABLE IF NOT EXISTS public.user_trading_settings (
    user_id INTEGER PRIMARY KEY REFERENCES public.users(id) ON DELETE CASCADE,
    order_size_mode VARCHAR(16) NOT NULL DEFAULT 'FIXED'
        CHECK (order_size_mode IN ('FIXED', 'RISK_BASED')),
    fixed_notional_usdt NUMERIC(24, 8) NOT NULL DEFAULT 100
        CHECK (fixed_notional_usdt > 0),
    risk_percentage NUMERIC(5, 2) NOT NULL DEFAULT 1
        CHECK (risk_percentage > 0 AND risk_percentage <= 5),
    default_leverage INTEGER NOT NULL DEFAULT 1
        CHECK (default_leverage BETWEEN 1 AND 125),
    execution_mode VARCHAR(16) NOT NULL DEFAULT 'CONFIRM'
        CHECK (execution_mode IN ('CONFIRM', 'AUTOMATIC')),
    auto_trade_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    kill_switch_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    live_trading_acknowledged_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.trade_executions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    signal_id BIGINT NOT NULL REFERENCES public.market_signals(id) ON DELETE RESTRICT,
    symbol VARCHAR(30) NOT NULL,
    side VARCHAR(5) NOT NULL CHECK (side IN ('LONG', 'SHORT')),
    entry_price NUMERIC(30, 12) NOT NULL CHECK (entry_price > 0),
    actual_fill_price NUMERIC(30, 12),
    quantity NUMERIC(30, 12) NOT NULL CHECK (quantity > 0),
    notional_usdt NUMERIC(30, 12) NOT NULL CHECK (notional_usdt > 0),
    leverage INTEGER NOT NULL CHECK (leverage BETWEEN 1 AND 125),
    stop_loss NUMERIC(30, 12) NOT NULL CHECK (stop_loss > 0),
    take_profit NUMERIC(30, 12) NOT NULL CHECK (take_profit > 0),
    binance_order_id VARCHAR(64),
    tp_order_id VARCHAR(64),
    sl_order_id VARCHAR(64),
    client_order_id VARCHAR(36) NOT NULL,
    execution_status VARCHAR(32) NOT NULL DEFAULT 'AWAITING_CONFIRMATION'
        CHECK (execution_status IN (
            'AWAITING_CONFIRMATION', 'EXECUTING', 'ENTRY_FILLED', 'PROTECTED',
            'FAILED', 'PROTECTION_FAILED', 'REJECTED', 'CANCELLED'
        )),
    execution_mode VARCHAR(16) NOT NULL CHECK (execution_mode IN ('CONFIRM', 'AUTOMATIC')),
    error_code VARCHAR(64),
    error_message TEXT,
    user_confirmed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, signal_id),
    UNIQUE (client_order_id)
);

CREATE INDEX IF NOT EXISTS trade_executions_user_created_idx
    ON public.trade_executions (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS trade_executions_user_status_idx
    ON public.trade_executions (user_id, execution_status, created_at DESC);

