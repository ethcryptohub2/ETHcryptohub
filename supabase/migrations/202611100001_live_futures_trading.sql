REVOKE ALL ON SEQUENCE public.trade_executions_id_seq FROM anon, authenticated;

DROP POLICY IF EXISTS user_trading_settings_self ON public.user_trading_settings;
CREATE POLICY user_trading_settings_self
    ON public.user_trading_settings FOR ALL TO authenticated
    USING (
        CASE WHEN (auth.jwt() ->> 'app_user_id') ~ '^[0-9]+$'
        THEN (auth.jwt() ->> 'app_user_id')::INTEGER = user_id ELSE FALSE END
    )
    WITH CHECK (
        CASE WHEN (auth.jwt() ->> 'app_user_id') ~ '^[0-9]+$'
        THEN (auth.jwt() ->> 'app_user_id')::INTEGER = user_id ELSE FALSE END
    );

DROP POLICY IF EXISTS trade_executions_self_read ON public.trade_executions;
CREATE POLICY trade_executions_self_read
    ON public.trade_executions FOR SELECT TO authenticated
    USING (
        CASE WHEN (auth.jwt() ->> 'app_user_id') ~ '^[0-9]+$'
        THEN (auth.jwt() ->> 'app_user_id')::INTEGER = user_id ELSE FALSE END
    );
