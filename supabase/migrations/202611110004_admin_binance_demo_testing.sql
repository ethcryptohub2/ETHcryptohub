CREATE TABLE IF NOT EXISTS public.admin_binance_demo_test_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    exchange VARCHAR(16) NOT NULL DEFAULT 'BINANCE' CHECK (exchange = 'BINANCE'),
    environment VARCHAR(8) NOT NULL DEFAULT 'DEMO' CHECK (environment = 'DEMO'),
    api_key_ciphertext TEXT,
    api_secret_ciphertext TEXT,
    api_key_suffix VARCHAR(8),
    owner_confirmed_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (
        (revoked_at IS NULL AND api_key_ciphertext IS NOT NULL
            AND api_secret_ciphertext IS NOT NULL AND api_key_suffix IS NOT NULL)
        OR
        (revoked_at IS NOT NULL AND api_key_ciphertext IS NULL
            AND api_secret_ciphertext IS NULL AND api_key_suffix IS NULL)
    ),
    UNIQUE (id, admin_user_id),
    UNIQUE (admin_user_id, exchange, environment)
);

CREATE TABLE IF NOT EXISTS public.admin_demo_test_account_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    admin_user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    event_type VARCHAR(40) NOT NULL
        CHECK (event_type IN ('CREDENTIALS_SAVED', 'CREDENTIALS_REVOKED')),
    safe_details JSONB NOT NULL DEFAULT '{}'::JSONB
        CHECK (jsonb_typeof(safe_details) = 'object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (account_id, admin_user_id)
        REFERENCES public.admin_binance_demo_test_accounts (id, admin_user_id)
        ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS admin_demo_test_account_events_admin_created_idx
    ON public.admin_demo_test_account_events (admin_user_id, account_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.admin_demo_test_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    test_account_id BIGINT NOT NULL,
    exchange VARCHAR(16) NOT NULL DEFAULT 'BINANCE' CHECK (exchange = 'BINANCE'),
    environment VARCHAR(8) NOT NULL DEFAULT 'DEMO' CHECK (environment = 'DEMO'),
    session_status VARCHAR(32) NOT NULL DEFAULT 'CREATED'
        CHECK (session_status IN (
            'CREATED', 'AUTHORIZED', 'RUNNING', 'RECONCILIATION_REQUIRED',
            'PASSED', 'FAILED', 'REVOKED', 'EXPIRED'
        )),
    symbol VARCHAR(30),
    direction VARCHAR(5) CHECK (direction IN ('LONG', 'SHORT')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at TIMESTAMPTZ,
    authorization_expires_at TIMESTAMPTZ,
    ended_at TIMESTAMPTZ,
    result_summary TEXT,
    UNIQUE (id, admin_user_id),
    FOREIGN KEY (test_account_id, admin_user_id)
        REFERENCES public.admin_binance_demo_test_accounts (id, admin_user_id)
        ON DELETE RESTRICT,
    CHECK ((symbol IS NULL) = (direction IS NULL)),
    CHECK (authorization_expires_at IS NULL OR authorization_expires_at > created_at)
);

CREATE TABLE IF NOT EXISTS public.admin_demo_test_authorizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    admin_user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    exchange VARCHAR(16) NOT NULL DEFAULT 'BINANCE' CHECK (exchange = 'BINANCE'),
    environment VARCHAR(8) NOT NULL DEFAULT 'DEMO' CHECK (environment = 'DEMO'),
    permitted_actions TEXT[] NOT NULL
        CHECK (
            cardinality(permitted_actions) BETWEEN 1 AND 3
            AND permitted_actions <@ ARRAY['START_TEST', 'RECONCILE', 'REVOKE']::TEXT[]
        ),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    UNIQUE (id, admin_user_id, session_id),
    FOREIGN KEY (session_id, admin_user_id)
        REFERENCES public.admin_demo_test_sessions (id, admin_user_id)
        ON DELETE RESTRICT,
    CHECK (expires_at > created_at),
    CHECK (expires_at <= created_at + INTERVAL '15 minutes'),
    CHECK (revoked_at IS NULL OR revoked_at >= created_at),
    CHECK (consumed_at IS NULL OR consumed_at >= created_at)
);

CREATE INDEX IF NOT EXISTS admin_demo_test_authorizations_active_idx
    ON public.admin_demo_test_authorizations (admin_user_id, session_id, expires_at DESC)
    WHERE revoked_at IS NULL;

CREATE TABLE IF NOT EXISTS public.admin_demo_test_executions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL UNIQUE,
    admin_user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    authorization_id BIGINT NOT NULL,
    exchange VARCHAR(16) NOT NULL DEFAULT 'BINANCE' CHECK (exchange = 'BINANCE'),
    environment VARCHAR(8) NOT NULL DEFAULT 'DEMO' CHECK (environment = 'DEMO'),
    symbol VARCHAR(30) NOT NULL CHECK (symbol ~ '^[A-Z0-9]{2,30}$'),
    direction VARCHAR(5) NOT NULL CHECK (direction IN ('LONG', 'SHORT')),
    quantity NUMERIC(30, 12) NOT NULL CHECK (quantity > 0),
    entry_client_order_id VARCHAR(36) NOT NULL UNIQUE,
    entry_exchange_order_id VARCHAR(64),
    execution_status VARCHAR(32) NOT NULL DEFAULT 'CREATED'
        CHECK (execution_status IN (
            'CREATED', 'ENTRY_SUBMITTING', 'ENTRY_UNKNOWN', 'ENTRY_FILLED',
            'PROTECTED', 'RECONCILIATION_REQUIRED', 'CLOSED', 'FAILED', 'REVOKED'
        )),
    stop_algo_order_id VARCHAR(64),
    tp3_algo_order_id VARCHAR(64),
    trailing_algo_order_id VARCHAR(64),
    stop_client_algo_id VARCHAR(36) NOT NULL,
    tp3_client_algo_id VARCHAR(36) NOT NULL,
    trailing_client_algo_id VARCHAR(36) NOT NULL,
    entry_price NUMERIC(30, 12) NOT NULL CHECK (entry_price > 0),
    stop_loss NUMERIC(30, 12) NOT NULL CHECK (stop_loss > 0),
    tp1_price NUMERIC(30, 12) NOT NULL CHECK (tp1_price > 0),
    tp2_price NUMERIC(30, 12) NOT NULL CHECK (tp2_price > 0),
    tp3_price NUMERIC(30, 12) NOT NULL CHECK (tp3_price > 0),
    tick_size NUMERIC(30, 12) NOT NULL CHECK (tick_size > 0),
    leverage INTEGER NOT NULL DEFAULT 1 CHECK (leverage BETWEEN 1 AND 20),
    tp1_reached_at TIMESTAMPTZ,
    tp2_reached_at TIMESTAMPTZ,
    protection_status VARCHAR(32) NOT NULL DEFAULT 'PENDING'
        CHECK (protection_status IN ('PENDING', 'PROTECTED', 'TRAILING', 'FAILED', 'CLOSED')),
    reconcile_lock_token UUID,
    reconcile_lock_until TIMESTAMPTZ,
    last_reconciled_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ,
    UNIQUE (id, admin_user_id, session_id),
    FOREIGN KEY (session_id, admin_user_id)
        REFERENCES public.admin_demo_test_sessions (id, admin_user_id)
        ON DELETE RESTRICT,
    FOREIGN KEY (authorization_id, admin_user_id, session_id)
        REFERENCES public.admin_demo_test_authorizations (id, admin_user_id, session_id)
        ON DELETE RESTRICT,
    CHECK ((reconcile_lock_token IS NULL) = (reconcile_lock_until IS NULL)),
    CHECK (
        (direction = 'LONG' AND stop_loss < entry_price AND entry_price < tp1_price
            AND tp1_price < tp2_price AND tp2_price < tp3_price)
        OR
        (direction = 'SHORT' AND tp3_price < tp2_price AND tp2_price < tp1_price
            AND tp1_price < entry_price AND entry_price < stop_loss)
    )
);

