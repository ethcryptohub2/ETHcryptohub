CREATE OR REPLACE FUNCTION public.authorize_admin_demo_test_action(
    p_admin_user_id INTEGER,
    p_session_id BIGINT,
    p_authorization_id BIGINT,
    p_action TEXT
) RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $function$
DECLARE
    authorized BOOLEAN := FALSE;
    affected_rows INTEGER := 0;
BEGIN
    IF p_action NOT IN ('START_TEST', 'RECONCILE') THEN
        RETURN FALSE;
    END IF;

    IF p_action = 'START_TEST' THEN
        UPDATE public.admin_demo_test_authorizations a
           SET consumed_at = CURRENT_TIMESTAMP
          FROM public.admin_demo_test_sessions s,
               public.admin_binance_demo_test_accounts c
         WHERE a.id = p_authorization_id
           AND a.session_id = p_session_id
           AND a.admin_user_id = p_admin_user_id
           AND a.exchange = 'BINANCE' AND a.environment = 'DEMO'
           AND p_action = ANY(a.permitted_actions)
           AND a.consumed_at IS NULL
           AND a.revoked_at IS NULL
           AND a.expires_at > CURRENT_TIMESTAMP
           AND s.id = a.session_id
           AND s.admin_user_id = a.admin_user_id
           AND s.session_status IN ('CREATED', 'AUTHORIZED')
           AND c.id = s.test_account_id
           AND c.admin_user_id = s.admin_user_id
           AND c.exchange = 'BINANCE' AND c.environment = 'DEMO'
           AND c.owner_confirmed_at IS NOT NULL AND c.revoked_at IS NULL;

        GET DIAGNOSTICS affected_rows = ROW_COUNT;
        authorized := affected_rows = 1;
        IF NOT authorized THEN
            RETURN FALSE;
        END IF;

        UPDATE public.admin_demo_test_sessions
           SET session_status = 'RUNNING',
               started_at = COALESCE(started_at, CURRENT_TIMESTAMP)
         WHERE id = p_session_id
           AND admin_user_id = p_admin_user_id
           AND session_status IN ('CREATED', 'AUTHORIZED');
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Admin Demo session state changed during authorization';
        END IF;

        INSERT INTO public.admin_demo_test_events (
            session_id, authorization_id, admin_user_id, event_type, event_status, safe_details
        ) VALUES (
            p_session_id, p_authorization_id, p_admin_user_id,
            'TEST_STARTED', 'SUCCEEDED',
            '{"exchange":"BINANCE","environment":"DEMO","authorizationConsumed":true}'::JSONB
        );
        RETURN TRUE;
    END IF;

    PERFORM 1
      FROM public.admin_demo_test_authorizations a
      JOIN public.admin_demo_test_sessions s
        ON s.id = a.session_id AND s.admin_user_id = a.admin_user_id
     WHERE a.id = p_authorization_id
       AND a.session_id = p_session_id
       AND a.admin_user_id = p_admin_user_id
       AND a.exchange = 'BINANCE' AND a.environment = 'DEMO'
       AND p_action = ANY(a.permitted_actions)
       AND a.consumed_at IS NOT NULL
       AND a.revoked_at IS NULL
       AND a.expires_at > CURRENT_TIMESTAMP
       AND s.session_status IN ('RUNNING', 'RECONCILIATION_REQUIRED')
     FOR UPDATE OF a, s;
    RETURN FOUND;
END;
$function$;

