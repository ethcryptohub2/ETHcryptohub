CREATE OR REPLACE FUNCTION public.authorize_admin_demo_exchange_action(
    p_admin_user_id INTEGER,
    p_admin_scope TEXT,
    p_session_id BIGINT,
    p_authorization_id BIGINT,
    p_provider public.admin_demo_provider,
    p_environment TEXT,
    p_action TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
    v_authorization_id BIGINT;
BEGIN
    IF COALESCE(auth.role(), '') <> 'service_role'
       OR p_admin_scope <> 'ADMIN'
       OR p_action NOT IN ('START_TEST', 'RECONCILE') THEN
        RETURN FALSE;
    END IF;

    SELECT a.id
      INTO v_authorization_id
      FROM public.admin_demo_exchange_authorizations AS a
      JOIN public.admin_demo_exchange_sessions AS s
        ON s.id = a.session_id
       AND s.admin_user_id = a.admin_user_id
       AND s.admin_scope = a.admin_scope
       AND s.provider = a.provider
       AND s.environment = a.environment
      JOIN public.admin_demo_exchange_credentials AS c
        ON c.id = s.credential_id
       AND c.admin_user_id = s.admin_user_id
       AND c.admin_scope = s.admin_scope
       AND c.provider = s.provider
       AND c.environment = s.environment
      JOIN public.admin_demo_identities AS i
        ON i.admin_user_id = a.admin_user_id
       AND i.admin_scope = a.admin_scope
     WHERE a.id = p_authorization_id
       AND a.session_id = p_session_id
       AND a.admin_user_id = p_admin_user_id
       AND a.admin_scope = p_admin_scope
       AND a.provider = p_provider
       AND a.environment = p_environment
       AND p_action = ANY(a.permitted_actions)
       AND a.revoked_at IS NULL
       AND a.expires_at > CURRENT_TIMESTAMP
       AND i.is_active
       AND s.is_enabled
       AND s.execution_mode = 'CONFIRM'
       AND c.is_enabled
       AND c.revoked_at IS NULL
     FOR UPDATE OF a, s;

    IF v_authorization_id IS NULL THEN
        RETURN FALSE;
    END IF;

    IF p_action = 'START_TEST' THEN
        UPDATE public.admin_demo_exchange_authorizations
           SET consumed_at = CURRENT_TIMESTAMP
         WHERE id = v_authorization_id
           AND consumed_at IS NULL
           AND p_action = ANY(permitted_actions);
        IF NOT FOUND THEN
            RETURN FALSE;
        END IF;

        UPDATE public.admin_demo_exchange_sessions
           SET session_status = 'RUNNING',
               started_at = COALESCE(started_at, CURRENT_TIMESTAMP)
         WHERE id = p_session_id
           AND admin_user_id = p_admin_user_id
           AND provider = p_provider
           AND environment = p_environment
           AND session_status IN ('CREATED', 'AUTHORIZED');
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Admin Demo session state changed during authorization';
        END IF;
    ELSE
        PERFORM 1
          FROM public.admin_demo_exchange_authorizations AS a
         WHERE a.id = v_authorization_id
           AND a.revoked_at IS NULL
           AND a.expires_at > CURRENT_TIMESTAMP
           AND a.consumed_at IS NOT NULL
           AND p_action = ANY(a.permitted_actions)
           AND EXISTS (
               SELECT 1
                 FROM public.admin_demo_exchange_sessions AS s
                WHERE s.id = p_session_id
                  AND s.admin_user_id = p_admin_user_id
                  AND s.provider = p_provider
                  AND s.environment = p_environment
                  AND s.session_status IN ('RUNNING', 'RECONCILIATION_REQUIRED')
           );
        IF NOT FOUND THEN
            RETURN FALSE;
        END IF;
    END IF;

    INSERT INTO public.admin_demo_exchange_audit_events (
        session_id, authorization_id, admin_user_id, admin_scope,
        provider, environment, event_type, event_status
    )
    VALUES (
        p_session_id, v_authorization_id, p_admin_user_id, p_admin_scope,
        p_provider, p_environment,
        CASE WHEN p_action = 'START_TEST' THEN 'TEST_STARTED' ELSE 'RECONCILIATION_STARTED' END,
        'SUCCEEDED'
    );

    RETURN TRUE;
END;
$$;

