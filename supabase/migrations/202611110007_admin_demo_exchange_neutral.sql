CREATE TYPE public.admin_demo_provider AS ENUM ('BINANCE', 'BYBIT', 'OKX', 'BITGET', 'GATE');

CREATE TABLE public.admin_demo_identities (
    admin_user_id INTEGER PRIMARY KEY REFERENCES public.users(id) ON DELETE CASCADE,
    admin_scope TEXT NOT NULL DEFAULT 'ADMIN' CHECK (admin_scope = 'ADMIN'),
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (admin_user_id, admin_scope)
);

CREATE TABLE public.admin_demo_exchange_credentials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_user_id INTEGER NOT NULL,
    admin_scope TEXT NOT NULL DEFAULT 'ADMIN' CHECK (admin_scope = 'ADMIN'),
    provider public.admin_demo_provider NOT NULL,
    environment TEXT NOT NULL,
    api_key_ciphertext TEXT NOT NULL,
    secret_key_ciphertext TEXT NOT NULL,
    passphrase_ciphertext TEXT,
    owner_confirmed_at TIMESTAMPTZ,
    is_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revoked_at TIMESTAMPTZ,
    CHECK (
        (provider = 'GATE' AND environment = 'TESTNET')
        OR (provider <> 'GATE' AND environment = 'DEMO')
    ),
    CHECK (NOT is_enabled OR owner_confirmed_at IS NOT NULL),
    UNIQUE (id, admin_user_id, admin_scope, provider, environment),
    FOREIGN KEY (admin_user_id, admin_scope)
        REFERENCES public.admin_demo_identities (admin_user_id, admin_scope)
        ON DELETE CASCADE
);

CREATE UNIQUE INDEX admin_demo_exchange_credentials_one_active_provider_idx
    ON public.admin_demo_exchange_credentials (admin_user_id, admin_scope, provider, environment)
    WHERE revoked_at IS NULL;

CREATE TABLE public.admin_demo_exchange_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_user_id INTEGER NOT NULL,
    admin_scope TEXT NOT NULL DEFAULT 'ADMIN' CHECK (admin_scope = 'ADMIN'),
    provider public.admin_demo_provider NOT NULL,
    environment TEXT NOT NULL,
    credential_id BIGINT NOT NULL,
    session_status TEXT NOT NULL DEFAULT 'CREATED'
        CHECK (session_status IN (
            'CREATED', 'AUTHORIZED', 'RUNNING', 'RECONCILIATION_REQUIRED',
            'PASSED', 'FAILED', 'REVOKED', 'EXPIRED'
        )),
    symbol VARCHAR(30),
    direction VARCHAR(5) CHECK (direction IN ('LONG', 'SHORT')),
    is_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    execution_mode TEXT NOT NULL DEFAULT 'CONFIRM' CHECK (execution_mode = 'CONFIRM'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at TIMESTAMPTZ,
    ended_at TIMESTAMPTZ,
    CHECK (
        (provider = 'GATE' AND environment = 'TESTNET')
        OR (provider <> 'GATE' AND environment = 'DEMO')
    ),
    UNIQUE (id, admin_user_id, admin_scope, provider, environment),
    FOREIGN KEY (admin_user_id, admin_scope)
        REFERENCES public.admin_demo_identities (admin_user_id, admin_scope)
        ON DELETE CASCADE,
    FOREIGN KEY (credential_id, admin_user_id, admin_scope, provider, environment)
        REFERENCES public.admin_demo_exchange_credentials
            (id, admin_user_id, admin_scope, provider, environment)
        ON DELETE RESTRICT,
    CHECK ((symbol IS NULL) = (direction IS NULL))
);

CREATE UNIQUE INDEX admin_demo_exchange_sessions_one_active_credential_idx
    ON public.admin_demo_exchange_sessions (credential_id)
    WHERE session_status IN ('AUTHORIZED', 'RUNNING', 'RECONCILIATION_REQUIRED');

CREATE TABLE public.admin_demo_exchange_authorizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    admin_user_id INTEGER NOT NULL,
    admin_scope TEXT NOT NULL DEFAULT 'ADMIN' CHECK (admin_scope = 'ADMIN'),
    provider public.admin_demo_provider NOT NULL,
    environment TEXT NOT NULL,
    permitted_actions TEXT[] NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (
        (provider = 'GATE' AND environment = 'TESTNET')
        OR (provider <> 'GATE' AND environment = 'DEMO')
    ),
    CHECK (
        cardinality(permitted_actions) > 0
        AND permitted_actions <@ ARRAY['START_TEST', 'RECONCILE']::TEXT[]
    ),
    CHECK (expires_at > created_at),
    CHECK (expires_at <= created_at + INTERVAL '15 minutes'),
    UNIQUE (id, session_id, admin_user_id, admin_scope, provider, environment),
    FOREIGN KEY (admin_user_id, admin_scope)
        REFERENCES public.admin_demo_identities (admin_user_id, admin_scope)
        ON DELETE CASCADE,
    FOREIGN KEY (session_id, admin_user_id, admin_scope, provider, environment)
        REFERENCES public.admin_demo_exchange_sessions
            (id, admin_user_id, admin_scope, provider, environment)
        ON DELETE CASCADE
);

CREATE UNIQUE INDEX admin_demo_exchange_authorizations_one_active_session_idx
    ON public.admin_demo_exchange_authorizations (session_id)
    WHERE revoked_at IS NULL;

CREATE TABLE public.admin_demo_exchange_executions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    authorization_id BIGINT NOT NULL,
    admin_user_id INTEGER NOT NULL,
    admin_scope TEXT NOT NULL DEFAULT 'ADMIN' CHECK (admin_scope = 'ADMIN'),
    provider public.admin_demo_provider NOT NULL,
    environment TEXT NOT NULL,
    entry_order_type TEXT NOT NULL CHECK (entry_order_type IN ('MARKET', 'LIMIT')),
    limit_entry_price NUMERIC(30, 12),
    symbol VARCHAR(30) NOT NULL CHECK (symbol ~ '^[A-Z0-9]{2,30}$'),
    direction VARCHAR(5) NOT NULL CHECK (direction IN ('LONG', 'SHORT')),
    quantity NUMERIC(30, 12) NOT NULL CHECK (quantity > 0),
    entry_price NUMERIC(30, 12) NOT NULL CHECK (entry_price > 0),
    entry_client_order_id VARCHAR(36) NOT NULL UNIQUE,
    entry_exchange_order_id VARCHAR(64),
    execution_status TEXT NOT NULL DEFAULT 'CREATED'
        CHECK (execution_status IN (
            'CREATED', 'ENTRY_SUBMITTING', 'ENTRY_UNKNOWN', 'ENTRY_FILLED',
            'PROTECTED', 'RECONCILIATION_REQUIRED', 'CLOSED', 'FAILED', 'REVOKED'
        )),
    stop_loss NUMERIC(30, 12) NOT NULL CHECK (stop_loss > 0),
    tp1_price NUMERIC(30, 12) NOT NULL CHECK (tp1_price > 0),
    tp2_price NUMERIC(30, 12) NOT NULL CHECK (tp2_price > 0),
    tp3_price NUMERIC(30, 12) NOT NULL CHECK (tp3_price > 0),
    tick_size NUMERIC(30, 12) NOT NULL CHECK (tick_size > 0),
    stop_client_order_id VARCHAR(36) NOT NULL UNIQUE,
    tp3_client_order_id VARCHAR(36) NOT NULL UNIQUE,
    trailing_client_order_id VARCHAR(36) NOT NULL UNIQUE,
    stop_protection_id VARCHAR(64),
    tp3_protection_id VARCHAR(64),
    trailing_protection_id VARCHAR(64),
    protection_status TEXT NOT NULL DEFAULT 'PENDING'
        CHECK (protection_status IN ('PENDING', 'PROTECTED', 'TRAILING', 'FAILED', 'CLOSED')),
    tp1_reached_at TIMESTAMPTZ,
    tp2_reached_at TIMESTAMPTZ,
    reconcile_lock_token UUID,
    reconcile_lock_until TIMESTAMPTZ,
    is_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    execution_mode TEXT NOT NULL DEFAULT 'CONFIRM' CHECK (execution_mode = 'CONFIRM'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ,
    CHECK (
        (provider = 'GATE' AND environment = 'TESTNET')
        OR (provider <> 'GATE' AND environment = 'DEMO')
    ),
    FOREIGN KEY (admin_user_id, admin_scope)
        REFERENCES public.admin_demo_identities (admin_user_id, admin_scope)
        ON DELETE CASCADE,
    UNIQUE (session_id),
    CHECK ((reconcile_lock_token IS NULL) = (reconcile_lock_until IS NULL)),
    CHECK (
        (direction = 'LONG' AND stop_loss < entry_price AND entry_price < tp1_price
            AND tp1_price < tp2_price AND tp2_price < tp3_price)
        OR
        (direction = 'SHORT' AND tp3_price < tp2_price AND tp2_price < tp1_price
            AND tp1_price < entry_price AND entry_price < stop_loss)
    ),
    CHECK ((entry_order_type = 'LIMIT') = (limit_entry_price IS NOT NULL)),
    CHECK (limit_entry_price IS NULL OR limit_entry_price > 0),
    FOREIGN KEY (session_id, admin_user_id, admin_scope, provider, environment)
        REFERENCES public.admin_demo_exchange_sessions
            (id, admin_user_id, admin_scope, provider, environment)
        ON DELETE CASCADE,
    FOREIGN KEY (authorization_id, session_id, admin_user_id, admin_scope, provider, environment)
        REFERENCES public.admin_demo_exchange_authorizations
            (id, session_id, admin_user_id, admin_scope, provider, environment)
        ON DELETE RESTRICT
);

CREATE TABLE public.admin_demo_exchange_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT,
    authorization_id BIGINT,
    admin_user_id INTEGER NOT NULL,
    admin_scope TEXT NOT NULL DEFAULT 'ADMIN' CHECK (admin_scope = 'ADMIN'),
    provider public.admin_demo_provider NOT NULL,
    environment TEXT NOT NULL,
    event_type TEXT NOT NULL CHECK (event_type IN (
        'CREDENTIAL_SAVED', 'CREDENTIAL_REVOKED', 'CONNECTION_TESTED',
        'BALANCE_READ', 'INSTRUMENTS_READ', 'POSITIONS_READ', 'PREFLIGHT_COMPLETED',
        'AUTHORIZATION_CREATED', 'AUTHORIZATION_REVOKED', 'TEST_STARTED',
        'ENTRY_SUBMITTED', 'ENTRY_RECONCILED', 'PROTECTION_VERIFIED',
        'RECONCILIATION_STARTED', 'RECONCILIATION_REQUIRED', 'POSITION_CLOSED',
        'TEST_PASSED', 'TEST_FAILED', 'EXECUTION_BLOCKED'
    )),
    event_status TEXT NOT NULL CHECK (event_status IN ('SUCCEEDED', 'FAILED', 'UNCERTAIN', 'BLOCKED')),
