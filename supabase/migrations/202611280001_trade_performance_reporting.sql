-- SmartExit Admin-Only Binance Demo Trade Performance & Analytics Migration
-- Adds financial tracking columns to public.trade_executions and reconciliation cache table

DO $$
BEGIN
    IF to_regclass('public.trade_executions') IS NULL THEN
        RAISE EXCEPTION 'Table public.trade_executions does not exist.';
    END IF;
END;
$$;

ALTER TABLE public.trade_executions
    ADD COLUMN IF NOT EXISTS exit_reason VARCHAR(32),
    ADD COLUMN IF NOT EXISTS funding_fee_usdt NUMERIC(30, 12) DEFAULT 0,
    ADD COLUMN IF NOT EXISTS net_realized_pnl NUMERIC(30, 12),
    ADD COLUMN IF NOT EXISTS tp3_reached_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS reconciliation_status VARCHAR(32) DEFAULT 'PENDING';

CREATE INDEX IF NOT EXISTS trade_executions_reconcile_status_idx
    ON public.trade_executions (exchange, environment, reconciliation_status, created_at DESC);

CREATE INDEX IF NOT EXISTS trade_executions_closed_at_idx
    ON public.trade_executions (closed_at DESC)
    WHERE closed_at IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.binance_demo_reconciliation_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    symbol VARCHAR(30) NOT NULL,
    record_type VARCHAR(32) NOT NULL,
    exchange_id VARCHAR(64) NOT NULL,
    order_id VARCHAR(64),
    client_order_id VARCHAR(64),
    trade_time TIMESTAMPTZ NOT NULL,
    amount NUMERIC(30, 12),
    asset VARCHAR(16) DEFAULT 'USDT',
    raw_payload JSONB NOT NULL DEFAULT '{}'::JSONB,
    matched_execution_id BIGINT REFERENCES public.trade_executions(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, record_type, exchange_id)
);

CREATE INDEX IF NOT EXISTS binance_demo_reconcile_time_idx
    ON public.binance_demo_reconciliation_records (user_id, trade_time DESC);

CREATE INDEX IF NOT EXISTS binance_demo_reconcile_symbol_idx
    ON public.binance_demo_reconciliation_records (user_id, symbol, trade_time DESC);

CREATE INDEX IF NOT EXISTS binance_demo_reconcile_matched_idx
    ON public.binance_demo_reconciliation_records (matched_execution_id);

ALTER TABLE public.binance_demo_reconciliation_records ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.binance_demo_reconciliation_records FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.binance_demo_reconciliation_records_id_seq FROM anon, authenticated;
